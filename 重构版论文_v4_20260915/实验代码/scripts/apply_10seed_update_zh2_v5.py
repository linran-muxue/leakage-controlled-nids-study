        "|---|---:|---:|---|---|---|---|---:|---:|---:|",
        "| RCCF − 等权 χ² 森林 | −0.000456 | 0.001152 | [−0.001280, +0.000368] | [−0.001124, +0.000212] | 等价 | 等价 | 0.001146 | −0.40 | 5 / 5 |",
