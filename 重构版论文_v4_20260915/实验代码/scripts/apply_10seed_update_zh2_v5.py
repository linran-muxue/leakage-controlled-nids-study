        "有三行值得说明。**功效**：在十个种子与实测标准差下，80% 功效可检出的最小差异为 0.00115 至 0.00161 Macro-F1，更小的效应会被漏检——这正是必须显式声明等价边界、而不能用「检验不显著」代替等价结论的原因。"
